namespace TelegramBOT.Domain.Teams.TeamCard
{
    /// <summary>
    /// Сводная (обобщённая) статистика команды.
    /// Содержит усреднённые показатели результативности матчей
    /// и используется как базовый блок для оценки силы и стиля команды.
    /// </summary>
    public class TeamSummaryStats
    {
        /// <summary>
        /// Средний общий тотал шайб за матч.
        /// Сумма шайб обеих команд, усреднённая по всем матчам выборки.
        /// </summary>
        public double AvgTotal { get; set; }

        /// <summary>
        /// Средний индивидуальный тотал команды за матч.
        /// Показывает, сколько шайб в среднем забивает команда.
        /// </summary>
        public double TeamTotal { get; set; }

        /// <summary>
        /// Средний индивидуальный тотал соперников за матч.
        /// Показывает, сколько шайб в среднем команда пропускает.
        /// </summary>
        public double OppTotal { get; set; }
    }
}
